// Standard GGUF / GGML quantization block layouts and codebook tables.
// Standalone definitions for InkEngine (zero runtime dependency on ggml/llama.cpp).

enum GGMLType : uint32_t {
    GGML_TYPE_F32     = 0,
    GGML_TYPE_F16     = 1,
    GGML_TYPE_Q4_0    = 2,
    GGML_TYPE_Q8_0    = 8,
    GGML_TYPE_Q4_K    = 12,
    GGML_TYPE_Q5_K    = 13,
    GGML_TYPE_Q6_K    = 14,
    GGML_TYPE_IQ2_XXS = 16,
    GGML_TYPE_IQ2_XS  = 17,
    GGML_TYPE_IQ3_XXS = 18,
    GGML_TYPE_IQ4_NL  = 20,
    GGML_TYPE_IQ2_S   = 22,
    GGML_TYPE_BF16    = 30,
    GGML_TYPE_NVFP4   = 40,
};

#pragma pack(push, 1)
struct BlockQ4_0    { uint16_t d; uint8_t qs[16]; };                                       // 18 B / 32
struct BlockQ8_0    { uint16_t d; int8_t qs[32]; };                                        // 34 B / 32
struct BlockQ8_1    { uint16_t d; uint16_t s; int8_t qs[32]; };                            // 36 B / 32
struct BlockQ4_K    { uint16_t d; uint16_t dmin; uint8_t scales[12]; uint8_t qs[128]; };   // 144 B / 256
struct BlockQ5_K    { uint16_t d; uint16_t dmin; uint8_t scales[12]; uint8_t qh[32]; uint8_t qs[128]; }; // 176 B / 256
struct BlockQ6_K    { uint8_t ql[128]; uint8_t qh[64]; int8_t scales[16]; uint16_t d; };   // 210 B / 256
struct BlockIQ2_XXS { uint16_t d; uint16_t qs[32]; };                                      // 66 B / 256
struct BlockIQ2_XS  { uint16_t d; uint16_t qs[32]; uint8_t scales[8]; };                   // 74 B / 256
struct BlockIQ2_S   { uint16_t d; uint8_t qs[64]; uint8_t qh[8]; uint8_t scales[8]; };     // 82 B / 256
struct BlockIQ3_XXS { uint16_t d; uint8_t qs[96]; };                                       // 98 B / 256
struct BlockIQ4_NL  { uint16_t d; uint8_t qs[16]; };                                       // 18 B / 32
struct BlockNVFP4   { uint8_t d[4]; uint8_t qs[32]; };                                     // 36 B / 64
#pragma pack(pop)

static_assert(sizeof(BlockQ4_0)    == 18,  "BlockQ4_0 size");
static_assert(sizeof(BlockQ8_0)    == 34,  "BlockQ8_0 size");
static_assert(sizeof(BlockQ8_1)    == 36,  "BlockQ8_1 size");
static_assert(sizeof(BlockQ4_K)    == 144, "BlockQ4_K size");
static_assert(sizeof(BlockQ5_K)    == 176, "BlockQ5_K size");
static_assert(sizeof(BlockQ6_K)    == 210, "BlockQ6_K size");
static_assert(sizeof(BlockIQ2_XXS) == 66,  "BlockIQ2_XXS size");
static_assert(sizeof(BlockIQ2_XS)  == 74,  "BlockIQ2_XS size");
static_assert(sizeof(BlockIQ2_S)   == 82,  "BlockIQ2_S size");
static_assert(sizeof(BlockIQ3_XXS) == 98,  "BlockIQ3_XXS size");
static_assert(sizeof(BlockIQ4_NL)  == 18,  "BlockIQ4_NL size");
static_assert(sizeof(BlockNVFP4)   == 36,  "BlockNVFP4 size");

inline size_t ggml_type_block_size(uint32_t t) {
    switch (t) {
        case GGML_TYPE_F32: case GGML_TYPE_F16: case GGML_TYPE_BF16: return 1;
        case GGML_TYPE_Q4_0: case GGML_TYPE_Q8_0: case GGML_TYPE_IQ4_NL: return 32;
        case GGML_TYPE_NVFP4: return 64;
        case GGML_TYPE_Q4_K: case GGML_TYPE_Q5_K: case GGML_TYPE_Q6_K:
        case GGML_TYPE_IQ2_XXS: case GGML_TYPE_IQ2_XS: case GGML_TYPE_IQ2_S: case GGML_TYPE_IQ3_XXS: return 256;
        default: return 1;
    }
}

inline size_t ggml_type_byte_size(uint32_t t) {
    switch (t) {
        case GGML_TYPE_F32: return 4; case GGML_TYPE_F16: return 2; case GGML_TYPE_BF16: return 2;
        case GGML_TYPE_Q4_0: return 18; case GGML_TYPE_Q8_0: return 34; case GGML_TYPE_IQ4_NL: return 18;
        case GGML_TYPE_NVFP4: return 36;
        case GGML_TYPE_Q4_K: return 144; case GGML_TYPE_Q5_K: return 176; case GGML_TYPE_Q6_K: return 210;
        case GGML_TYPE_IQ2_XXS: return 66; case GGML_TYPE_IQ2_XS: return 74; case GGML_TYPE_IQ2_S: return 82; case GGML_TYPE_IQ3_XXS: return 98;
        default: return 0;
    }
}

inline const char* ggml_type_name(uint32_t t) {
    switch (t) {
        case GGML_TYPE_F32: return "F32"; case GGML_TYPE_F16: return "F16"; case GGML_TYPE_BF16: return "BF16";
        case GGML_TYPE_Q4_0: return "Q4_0"; case GGML_TYPE_Q8_0: return "Q8_0"; case GGML_TYPE_Q4_K: return "Q4_K";
        case GGML_TYPE_Q5_K: return "Q5_K"; case GGML_TYPE_Q6_K: return "Q6_K"; case GGML_TYPE_IQ2_XXS: return "IQ2_XXS";
        case GGML_TYPE_IQ2_XS: return "IQ2_XS"; case GGML_TYPE_IQ2_S: return "IQ2_S"; case GGML_TYPE_IQ3_XXS: return "IQ3_XXS";
        case GGML_TYPE_IQ4_NL: return "IQ4_NL"; case GGML_TYPE_NVFP4: return "NVFP4";
        default: return "UNKNOWN";
    }
}

inline float fp16_to_fp32_host(uint16_t h) {
    uint32_t s = (uint32_t)(h & 0x8000u) << 16;
    uint32_t e = (h >> 10) & 0x1Fu;
    uint32_t m = h & 0x03FFu;
    uint32_t f;
    if (e == 0) {
        if (m == 0) { f = s; }
        else {
            e = 127 - 14;
            while ((m & 0x0400u) == 0) { m <<= 1; e--; }
            m &= 0x03FFu;
            f = s | (e << 23) | (m << 13);
        }
    } else if (e == 31) {
        f = s | 0x7F800000u | (m << 13);
    } else {
        f = s | ((e + 112) << 23) | (m << 13);
    }
    float res;
    std::memcpy(&res, &f, 4);
    return res;
}

inline uint16_t fp32_to_fp16_host(float v) {
    uint32_t f;
    std::memcpy(&f, &v, 4);
    uint32_t sign = (f >> 16) & 0x8000u;
    int exp = (int)((f >> 23) & 0xFFu) - 127 + 15;
    uint32_t mant = f & 0x007FFFFFu;
    if (exp <= 0) {
        if (exp < -10) return (uint16_t)sign;
        mant |= 0x00800000u;
        uint32_t shift = (uint32_t)(14 - exp);
        return (uint16_t)(sign | ((mant + (1u << (shift - 1))) >> shift));
    } else if (exp >= 31) {
        return (uint16_t)(sign | 0x7BFFu);
    }
    return (uint16_t)(sign | ((uint32_t)exp << 10) | ((mant + 0x00001000u) >> 13));
}

inline float bf16_to_fp32_host(uint16_t b) {
    uint32_t u = (uint32_t)b << 16;
    float r;
    std::memcpy(&r, &u, 4);
    return r;
}

inline void get_scale_min_k4(int j, const uint8_t* q, uint8_t& d, uint8_t& m) {
    if (j < 4) {
        d = q[j] & 63;
        m = q[j + 4] & 63;
    } else {
        d = (q[j + 4] & 0xF) | ((q[j - 4] >> 6) << 4);
        m = (q[j + 4] >> 4)  | ((q[j - 0] >> 6) << 4);
    }
}

